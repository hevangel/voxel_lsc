# Lands Department 5 m Digital Terrain Model -> js/terrain_data.js (world coordinates).
#
#   py fetch_dtm.py "<path to Digital Terrain Model.tif>"
#
# Source: CSDI dataset landsd_rcd_1638158088368_93806, "Digital Terrain Model (DTM)",
# HK1980 Grid (EPSG:2326), HKPD heights (EPSG:5738), 5 m cells, +-5 m accuracy,
# integer metres; elevated roads and vegetation canopy are included, buildings are not.
# Download (24 MB zip, 498 MB GeoTIFF + .tfw, origin E 800000 N 848000):
#   https://static.csdi.gov.hk/csdi-webpage/download/common/e9a836d098a3a9ccf55a7f61f69a93e71923c722fb94ddf7b36be83a67b99140
#
# World -> HK1980 is an affine fitted on three points converted with the LandsD
# transform API (https://www.geodetic.gov.hk/transform/v2/, wgsgeog -> hkgrid) from the
# satellite-grid formula in RESEARCH_NOTES.md:
#   (2, 55.85) -> E 836886.904 N 821033.936   (track centre)
#   (-200,-250) -> E 836684.811 N 821339.131
#   (250, 250)  -> E 837135.019 N 820840.209
# Output heights stay HKPD; the model puts y 0 at the track (TRACK_HKPD below).
import sys, os, base64
import numpy as np
from PIL import Image

Image.MAX_IMAGE_PIXELS = None
P = np.array([[2, 55.85], [-200, -250], [250, 250]], float)
EN = np.array([[836886.904, 821033.936], [836684.811, 821339.131], [837135.019, 820840.209]])
A = np.linalg.solve(np.c_[P, np.ones(3)], EN)          # [x z 1] @ A = [E N]
X0, Y0, CELL = 800000.0, 848000.0, 5.0                 # from the .tfw
TRACK_HKPD = 14.0                                      # DTM over the pitch and track

GRIDS = {  # name: (x0, x1, z0, z1, step)
    'near': (-700, 700, -800, 700, 5.0),               # campus + Kowloon Tong
    'far': (-4000, 4000, -4400, 1600, 20.0),           # Lion Rock, Beacon Hill, Kowloon
}

def sample(img, xs, zs, blur):
    gx, gz = np.meshgrid(xs, zs)
    en = np.stack([gx, gz, np.ones_like(gx)], -1) @ A
    col = (en[..., 0] - X0) / CELL - 0.5
    row = (Y0 - en[..., 1]) / CELL - 0.5
    c0, c1 = int(col.min()) - 4, int(col.max()) + 5
    r0, r1 = int(row.min()) - 4, int(row.max()) + 5
    sub = np.asarray(img.crop((c0, r0, c1, r1)), dtype=np.float64)
    sub[sub < 0] = 0.0                                  # sea / nodata
    for _ in range(blur):                               # soften the 1 m integer steps
        p = np.pad(sub, 1, mode='edge')
        sub = (p[:-2, :-2] + 2 * p[:-2, 1:-1] + p[:-2, 2:] + 2 * p[1:-1, :-2] + 4 * p[1:-1, 1:-1] +
               2 * p[1:-1, 2:] + p[2:, :-2] + 2 * p[2:, 1:-1] + p[2:, 2:]) / 16.0
    cc, rr = col - c0, row - r0
    i0, j0 = np.floor(rr).astype(int), np.floor(cc).astype(int)
    fr, fc = rr - i0, cc - j0
    return (sub[i0, j0] * (1 - fr) * (1 - fc) + sub[i0, j0 + 1] * (1 - fr) * fc +
            sub[i0 + 1, j0] * fr * (1 - fc) + sub[i0 + 1, j0 + 1] * fr * fc)

def main(tif):
    img = Image.open(tif)
    here = os.path.dirname(os.path.abspath(__file__))
    out = ['/* Generated by reference/data/fetch_dtm.py from the LandsD 5 m DTM (HKPD metres).',
           ' * Do not edit. Grid rows run north->south (z0 upward), columns west->east.',
           ' * Values: little-endian int16 decimetres, base64. */',
           'window.LSC_DTM = { trackHKPD: %.1f, grids: {' % TRACK_HKPD]
    for name, (xa, xb, za, zb, st) in GRIDS.items():
        xs = np.arange(xa, xb + st / 2, st); zs = np.arange(za, zb + st / 2, st)
        v = sample(img, xs, zs, 2 if name == 'near' else 1)
        q = np.round(v * 10).astype('<i2')
        b64 = base64.b64encode(q.tobytes()).decode()
        out.append("  %s: { x0: %g, z0: %g, step: %g, nx: %d, nz: %d, data: '%s' }," %
                   (name, xa, za, st, len(xs), len(zs), b64))
        print('%s %dx%d  %.1f..%.1f m' % (name, len(xs), len(zs), v.min(), v.max()))
        if name == 'near':
            np.save(os.path.join(here, 'dtm_near.npy'), v)
    out.append('} };')
    dst = os.path.join(here, '..', '..', 'js', 'terrain_data.js')
    with open(dst, 'w') as f:
        f.write('\n'.join(out) + '\n')
    print('->', os.path.normpath(dst), os.path.getsize(dst), 'bytes')

if __name__ == '__main__':
    main(sys.argv[1])
